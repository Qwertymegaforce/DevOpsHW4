#!/bin/sh
. "$(dirname "$0")/lib.sh"

step "Установка манифестов"
run "kubectl apply -f k8s/00-namespace.yaml -f k8s/10-tls.yaml -f k8s/20-backend.yaml -f k8s/30-frontend.yaml -f k8s/40-ingress.yaml"
run "kubectl -n $NS wait --for=condition=Ready certificate/counter-tls --timeout=120s"
run "kubectl -n $NS rollout status deploy/backend --timeout=180s && kubectl -n $NS rollout status deploy/frontend --timeout=180s"
run "kubectl -n $NS get deploy,rs,pods,svc,ingress,certificate,issuer -o wide"

step "1.1 HTTPS с собственным сертификатом, curl проверяет его без -k"
run "kubectl -n $NS get secret counter-tls -o jsonpath='{.data.ca\\.crt}' | base64 -d > ca.crt && openssl x509 -in ca.crt -noout -subject -issuer"
run "kubectl -n $NS get secret counter-tls -o jsonpath='{.data.tls\\.crt}' | base64 -d | openssl x509 -noout -subject -issuer -ext subjectAltName -dates"
note "без нашего CA curl сертификату не доверяет:"
run "curl -sS https://$HOST/ -o /dev/null"
note "с нашим CA — проверка проходит:"
run "curl -v --cacert ca.crt https://$HOST/ -o /dev/null 2>&1 | grep -E 'SSL connection|subject:|issuer:|SSL certificate verify|HTTP/2 [0-9]'"
run "curl -sS --cacert ca.crt https://$HOST/ | grep -o '<button[^>]*>[^<]*</button>'"
run "curl -sS --cacert ca.crt https://$HOST/api/counter; echo"
run "for i in 1 2 3; do curl -sS --cacert ca.crt -X POST https://$HOST/api/counter; echo; done"
run "curl -sS --cacert ca.crt https://$HOST/api/counter; echo"

step "1.2 backend снаружи доступен только через /api"
run "kubectl -n $NS get svc -o custom-columns=NAME:.metadata.name,TYPE:.spec.type,CLUSTER-IP:.spec.clusterIP,PORTS:.spec.ports[*].port"
run "kubectl -n $NS get ingress counter -o jsonpath='{range .spec.rules[*].http.paths[*]}{.path}{\" -> \"}{.backend.service.name}{\"\\n\"}{end}'"
note "/api/* уходит в backend, всё остальное — во frontend (у него нет /counter, отсюда 404 от Next.js):"
run "curl -s --cacert ca.crt -o /dev/null -w '%{http_code} %{content_type}\\n' https://$HOST/api/counter"
run "curl -s --cacert ca.crt -o /dev/null -w '%{http_code} %{content_type}\\n' https://$HOST/counter"
note "порт backend на нодах/хосте не опубликован:"
run "curl -sS --max-time 3 http://$HOST:9090/api/counter"

step "1.3 backend слушает порт 9090, порт задаётся ConfigMap без пересборки образа"
run "docker image inspect counter-backend:1.0.0 --format 'ENV в образе: {{.Config.Env}}'"
run "kubectl -n $NS get configmap backend -o jsonpath='{.data}'; echo"
run "kubectl -n $NS logs deploy/backend | grep -i 'running on'"
note "меняем порт на 9191: правим ConfigMap и containerPort (пробы и Service ссылаются на именованный порт http)"
run "kubectl -n $NS patch configmap backend --type merge -p '{\"data\":{\"PORT\":\"9191\"}}'"
run "kubectl -n $NS patch deploy backend --type json -p '[{\"op\":\"replace\",\"path\":\"/spec/template/spec/containers/0/ports/0/containerPort\",\"value\":9191}]'"
run "kubectl -n $NS annotate deploy backend kubernetes.io/change-cause='PORT 9090 -> 9191 (demo 1.3)' --overwrite"
run "kubectl -n $NS rollout status deploy/backend --timeout=120s"
settle backend
run "kubectl -n $NS logs -l app.kubernetes.io/name=backend --prefix | grep -i 'running on'"
run "kubectl -n $NS get endpointslices -l kubernetes.io/service-name=backend -o jsonpath='{range .items[*]}{.endpoints[*].addresses}{\" port \"}{.ports[*].port}{\"\\n\"}{end}'"
run "curl -sS --cacert ca.crt https://$HOST/api/counter; echo"
note "возвращаем 9090"
run "kubectl -n $NS patch configmap backend --type merge -p '{\"data\":{\"PORT\":\"9090\"}}'"
run "kubectl -n $NS patch deploy backend --type json -p '[{\"op\":\"replace\",\"path\":\"/spec/template/spec/containers/0/ports/0/containerPort\",\"value\":9090}]'"
run "kubectl -n $NS annotate deploy backend kubernetes.io/change-cause='PORT 9191 -> 9090 (revert demo 1.3)' --overwrite"
run "kubectl -n $NS rollout status deploy/backend --timeout=120s"
settle backend
run "kubectl -n $NS logs -l app.kubernetes.io/name=backend --prefix | grep -i 'running on'"

step "1.4 readiness/liveness: что происходит с трафиком, когда экземпляр перестаёт быть готовым"
run "kubectl -n $NS get deploy backend -o jsonpath='{range .spec.template.spec.containers[0]}startup:   {.startupProbe}{\"\\n\"}readiness: {.readinessProbe}{\"\\n\"}liveness:  {.livenessProbe}{\"\\n\"}{end}'"
run "kubectl -n $NS scale deploy backend --replicas=2 && kubectl -n $NS rollout status deploy/backend --timeout=120s"
A="$(kubectl -n $NS get pod -l app.kubernetes.io/name=backend --sort-by=.metadata.name -o jsonpath='{.items[0].metadata.name}')"
B="$(kubectl -n $NS get pod -l app.kubernetes.io/name=backend --sort-by=.metadata.name -o jsonpath='{.items[1].metadata.name}')"
note "счётчик у каждого пода свой (в памяти), поэтому по ответу видно, какой под ответил."
note "накручиваем счётчик пода $A до 100 напрямую, в обход Service:"
run "kubectl -n $NS exec $A -- python -c 'import urllib.request as u; [u.urlopen(u.Request(\"http://127.0.0.1:9090/api/counter\", method=\"POST\")) for _ in range(100)]; print(u.urlopen(\"http://127.0.0.1:9090/api/counter\").read().decode())'"
run "kubectl -n $NS get endpointslices -l kubernetes.io/service-name=backend -o jsonpath='{range .items[*].endpoints[*]}{.targetRef.name} ready={.conditions.ready}{\"\\n\"}{end}'"
loop 75 /tmp/counter-loop.txt &
LOOP=$!
sleep 4
NODE="$(kubectl -n $NS get pod $A -o jsonpath='{.spec.nodeName}')"
CID="$(kubectl -n $NS get pod $A -o jsonpath='{.status.containerStatuses[0].containerID}' | sed 's|.*://||')"
PID="$(docker exec $NODE crictl inspect -o go-template --template '{{.info.pid}}' $CID)"
note "$(date +%T) «вешаем» под $A: SIGSTOP процессу backend (pid $PID на ноде $NODE) — процесс жив, но не отвечает"
run "docker exec $NODE kill -STOP $PID"
sleep 14
note "$(date +%T) через ~10 с readiness-проба упала, под исключён из EndpointSlice:"
run "kubectl -n $NS get endpointslices -l kubernetes.io/service-name=backend -o jsonpath='{range .items[*].endpoints[*]}{.targetRef.name} ready={.conditions.ready}{\"\\n\"}{end}'"
run "kubectl -n $NS get pods -l app.kubernetes.io/name=backend"
wait $LOOP
note "лог запросов через ingress, 4 запроса в секунду (время, тело ответа, HTTP-код; 000 — таймаут curl 2 с)."
note "одинаковые подряд идущие ответы свёрнуты: «с-по xN»"
note "squash — функция из scripts/lib.sh, сворачивает подряд идущие одинаковые ответы"
printf '$ squash /tmp/counter-loop.txt\n'; squash /tmp/counter-loop.txt; echo
run "awk '{print \$NF}' /tmp/counter-loop.txt | sort | uniq -c"
note "liveness-проба тоже упала (3 x 10 с) — kubelet перезапустил зависший контейнер:"
run "kubectl -n $NS get pods -l app.kubernetes.io/name=backend"
run "kubectl -n $NS get events --field-selector involvedObject.name=$A --sort-by=.lastTimestamp | grep -E 'Unhealthy|Killing|Started' | tail -6"
run "kubectl -n $NS wait --for=condition=Ready pod/$A --timeout=120s"
run "kubectl -n $NS get endpointslices -l kubernetes.io/service-name=backend -o jsonpath='{range .items[*].endpoints[*]}{.targetRef.name} ready={.conditions.ready}{\"\\n\"}{end}'"
run "kubectl -n $NS scale deploy backend --replicas=1 && kubectl -n $NS rollout status deploy/backend"
finish
